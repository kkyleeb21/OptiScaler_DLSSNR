"""Generate the C++ byte guards from the readable installer specification (CPU only)."""
import argparse
import json
from pathlib import Path


def generate(spec):
    out = ['// Generated by generate-runtime-profiles.py; do not edit.', '#pragma once',
           'namespace DlssNr::Runtime {']
    for i, p in enumerate(spec['profiles']):
        sites = []
        for h in p['hunks'] + p['guards']:
            original = bytes.fromhex(h['expected_hex'])
            patched = 'replacement_hex' in h or 'replacement_parts' in h
            values = {original: 1 if patched else 3}
            if 'replacement_hex' in h:
                replacement = bytes.fromhex(h['replacement_hex'])
            elif 'replacement_parts' in h:
                replacement = b''.join(bytes.fromhex(x['hex']) if 'hex' in x else
                                        bytes.fromhex(x['fill_byte']) * x['count']
                                        for x in h['replacement_parts'])
            if patched:
                values[replacement] = values.get(replacement, 0) | 2
            for v in h.get('compatible_input_hex', []):
                v = bytes.fromhex(v)
                values[v] = values.get(v, 0) | (1 if patched else 3)
            offset = h['offset']
            rva, skip = offset, 0
            if offset >= 0x400:
                rva = -1
                for sec in p['sections']:
                    if sec['raw'] <= offset < sec['raw'] + sec['size']:
                        rva = offset - sec['raw'] + sec['rva']
                        break
                if not original:  # Append guard includes unmapped certificate/alignment padding.
                    sec = p['sections'][-1]
                    skip = sec['raw'] - offset
                    rva = sec['rva']
            if h.get('file_only'):
                rva = -1
            ident = f'P{i}G{len(sites)}'
            out.append(f'inline constexpr Bytes {ident}[]={{')
            for v, states in values.items():
                text = ''.join(f'\\x{x:02x}' for x in v)
                out.append(f'{{"{text}",{len(v)},{states}}},')
            out.append('};')
            append = 'true' if patched and not original else 'false'
            sites.append(f'{{{offset}u,{rva}ll,{skip}u,{append},{ident},sizeof({ident})/sizeof(Bytes)}},')
        out += [f'inline constexpr Guard P{i}Guards[]={{', *sites, '};']
    out.append('inline constexpr char Sampler310916[]="\\x41\\x83\\xbe\\x20\\x01\\x00\\x00\\x00\\x74\\x2c\\xf3\\x41\\x0f\\x10\\x86\\x24\\x01\\x00\\x00\\xf3\\x0f\\x10\\x0d\\x07\\x78\\x0b\\x00\\x0f\\x2f\\xc1\\x72\\x07\\x0f\\x28\\xcf\\xf3\\x0f\\x5d\\xc8\\xf3\\x0f\\x10\\x05\\x3b\\x8d\\x0b\\x00\\x0f\\x2f\\xc1\\x8b\\xd6\\x77\\x05\\xba\\x02\\x00\\x00\\x00";')
    out.append('inline constexpr Profile Profiles[]={')
    for i, p in enumerate(spec['profiles']):
        major, minor, build, rev = p['version']
        legacy = p['id'] == 'nr3108'
        grade = '{{0xb0de4,0},{0xb0da8,0},1}' if legacy else '{{0xdbe9c,0xdc12c},{0xdbe60,0xdc0f0},2}'
        sampler = '{0x1caf2,0,nullptr,0,0x21db4,0x21ddc}' if legacy else '{0x1cbd2,0x22022,Sampler310916,59,0x2206a,0x2208f}'
        out.append('{"%s",%du,%du,%s,%s,P%dGuards,sizeof(P%dGuards)/sizeof(Guard),%s,%s},' % (
            p['id'], (major << 16) | minor, (build << 16) | rev,
            'true' if legacy else 'false', 'true' if p['experimental'] else 'false', i, i, grade, sampler))
    return '\n'.join(out + ['};', '}']) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[3]
    spec = json.loads((Path(__file__).parent / 'runtime_patch_spec.json').read_text(encoding='utf-8-sig'))
    path = root / 'OptiScaler/dlssnr/RuntimeProfileData.h'
    content = generate(spec)
    if args.check:
        if path.read_text(encoding='utf-8') != content:
            raise SystemExit('Stale RuntimeProfileData.h; run generate-runtime-profiles.py')
    else:
        path.write_text(content, encoding='utf-8')
    print('Runtime profile guards verified.' if args.check else 'Runtime profile guards generated.')
